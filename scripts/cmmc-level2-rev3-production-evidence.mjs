import crypto from "node:crypto";
import fs from "node:fs";

const sourcePath = "docs/florida-class-d-lms/CMMC-LEVEL-2-REV3-PRODUCTION-EVIDENCE.json";
const humanPath = "docs/florida-class-d-lms/CMMC-LEVEL-2-REV3-PRODUCTION-EVIDENCE.md";
const digestPath = "docs/florida-class-d-lms/CMMC-LEVEL-2-REV3-PRODUCTION-EVIDENCE.sha256";
const vercelPath = "vercel.json";
const vercelIgnorePath = "scripts/vercel-ignore-build.sh";
const clerkConfigPath = "lib/clerk-runtime-config.ts";
const identityPath = "lib/identity-runtime.ts";
const layoutPath = "app/layout.tsx";
const proxyPath = "proxy.ts";

const mode = process.argv.includes("--write") ? "write" : "check";
const allowedStatuses = new Set([
  "implemented_source_evidence",
  "implemented_source_pending_postdeploy_validation",
  "partial_external_evidence_required",
  "external_evidence_required",
]);

function fail(message) {
  throw new Error(`Gate 34 failed: ${message}`);
}

function read(path) {
  if (!fs.existsSync(path)) fail(`missing required file ${path}`);
  return fs.readFileSync(path, "utf8");
}

function requireText(path, source, text, label = text) {
  if (!source.includes(text)) fail(`${path} missing ${label}`);
}

function forbidText(path, source, text, label = text) {
  if (source.includes(text)) fail(`${path} contains forbidden ${label}`);
}

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function renderMarkdown(data, digest) {
  const lines = [
    "# CMMC Level 2 Rev. 3 Production Evidence",
    "",
    "> Generated from `CMMC-LEVEL-2-REV3-PRODUCTION-EVIDENCE.json`. Do not edit this file manually.",
    "",
    `**Source SHA-256:** \`${digest}\``,
    "",
    "## Program",
    "",
    `- **Owner:** ${data.program.owner}`,
    `- **Repository:** \`${data.program.repository}\``,
    `- **Engineering baseline:** ${data.framework.engineeringBaseline}`,
    `- **Assessment baseline:** ${data.framework.assessmentBaseline}`,
    `- **NIST OSCAL source blob:** \`${data.framework.nistOscalSource.blobSha}\``,
    `- **Claim boundary:** ${data.program.claimBoundary}`,
    "",
    "## Release binding",
    "",
    `- **Previous validated source SHA:** \`${data.release.previousValidatedSourceSha}\``,
    `- **Merged production SHA:** \`${data.release.mergedProductionSha}\``,
    `- **Validated Vercel deployment:** \`${data.release.validatedVercelDeploymentId}\``,
    `- **Canonical domains:** ${data.release.canonicalDomains.join(", ")}`,
    `- **Florida Class D production authorized:** \`${String(data.release.regulatedClassDProductionAuthorized)}\``,
    `- **CUI processing authorized:** \`${String(data.release.cuiProcessingAuthorized)}\``,
    "",
    "## Evidence records",
    "",
  ];

  for (const record of data.records) {
    lines.push(
      `### ${record.id} — ${record.title}`,
      "",
      `- **Status:** \`${record.status}\``,
      `- **NIST SP 800-171 Rev. 3:** ${record.rev3.map((item) => `\`${item}\``).join(", ")}`,
      `- **CMMC Level 2 current crosswalk:** ${record.rev2.map((item) => `\`${item}\``).join(", ")}`,
      `- **Assessment methods:** ${record.methods.join(", ")}`,
      `- **Boundary:** ${record.boundary}`,
      "",
      `**Implementation:** ${record.implementation}`,
      "",
      "**Evidence:**",
    );
    for (const evidence of record.evidence) lines.push(`- \`${evidence}\``);
    lines.push("", `**Gap / remaining evidence:** ${record.gap}`, "");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

const sourceText = read(sourcePath);
let data;
try {
  data = JSON.parse(sourceText);
} catch (error) {
  fail(`${sourcePath} is not valid JSON: ${error instanceof Error ? error.message : String(error)}`);
}

if (data.schemaVersion !== "1.0") fail("production evidence schemaVersion must be 1.0");
if (data.program?.owner !== "OBSERRA EXECUTIVE PROTECTION & INTELLIGENCE LLC") fail("canonical legal owner is not preserved");
if (data.framework?.engineeringBaseline !== "NIST SP 800-171 Rev. 3") fail("Rev. 3 must remain the engineering baseline");
if (data.framework?.assessmentBaseline !== "NIST SP 800-171A Rev. 3") fail("Rev. 3 assessment baseline is missing");
if (!/^[0-9a-f]{40}$/.test(data.framework?.nistOscalSource?.blobSha ?? "")) fail("NIST OSCAL provenance blob SHA is invalid");
if (data.release?.regulatedClassDProductionAuthorized !== false) fail("Florida Class D production must remain fail closed");
if (data.release?.cuiProcessingAuthorized !== false) fail("CUI processing must remain unauthorized until formal scope and authorization exist");
if (JSON.stringify(data.release?.canonicalDomains) !== JSON.stringify(["www.obserrallc.com", "obserrallc.com"])) fail("canonical domain set drifted");
if (!Array.isArray(data.records) || data.records.length < 8) fail("production evidence records are incomplete");

const recordIds = new Set();
for (const record of data.records) {
  if (!/^PRE-[0-9]{3}$/.test(record.id ?? "")) fail(`invalid record id ${record.id}`);
  if (recordIds.has(record.id)) fail(`duplicate record id ${record.id}`);
  recordIds.add(record.id);
  if (!allowedStatuses.has(record.status)) fail(`${record.id} has unsupported status ${record.status}`);
  if (!Array.isArray(record.rev3) || record.rev3.length === 0 || record.rev3.some((id) => !/^03\.[0-9]{2}\.[0-9]{2}$/.test(id))) fail(`${record.id} has invalid Rev. 3 mapping`);
  if (!Array.isArray(record.rev2) || record.rev2.length === 0 || record.rev2.some((id) => !/^3\.[0-9]+\.[0-9]+$/.test(id))) fail(`${record.id} has invalid CMMC Level 2 crosswalk mapping`);
  if (!Array.isArray(record.methods) || record.methods.length === 0) fail(`${record.id} lacks assessment methods`);
  if (!Array.isArray(record.evidence) || record.evidence.length === 0) fail(`${record.id} lacks evidence references`);
  for (const evidence of record.evidence) {
    if (!fs.existsSync(evidence)) fail(`${record.id} references missing evidence ${evidence}`);
  }
}

for (const forbidden of ["sk_live_", "sk_test_", "STRIPE_WEBHOOK_SECRET=", "STRIPE_SECRET_KEY="]) {
  if (sourceText.includes(forbidden)) fail(`machine-readable evidence contains secret-like material ${forbidden}`);
}

const vercelConfig = JSON.parse(read(vercelPath));
const expectedCanonicalAliases = ["www.obserrallc.com", "obserrallc.com"];
if (JSON.stringify(vercelConfig.alias) !== JSON.stringify(expectedCanonicalAliases)) {
  fail("canonical aliases must remain exactly scoped to www.obserrallc.com and obserrallc.com");
}
if (vercelConfig.ignoreCommand !== "sh scripts/vercel-ignore-build.sh") {
  fail("ignoreCommand must delegate to the bounded canonical-project guard script");
}
if (vercelConfig.ignoreCommand.length > 256) {
  fail("ignoreCommand exceeds Vercel's 256-character schema limit");
}
const vercelIgnore = read(vercelIgnorePath);
requireText(vercelIgnorePath, vercelIgnore, "${VERCEL_PROJECT_ID:-}", "project-aware ignored-build guard");
requireText(vercelIgnorePath, vercelIgnore, "prj_FfAnssVJU8pcJydGNJHmCliP6Yme", "canonical Vercel project guard");
requireText(vercelIgnorePath, vercelIgnore, "${VERCEL_ENV:-}", "environment-aware ignored-build guard");
requireText(vercelIgnorePath, vercelIgnore, '!= "production"', "production-only alias deployment guard");
requireText(vercelIgnorePath, vercelIgnore, "exit 0", "fail-closed noncanonical deployment suppression");
requireText(vercelIgnorePath, vercelIgnore, "exit 1", "canonical changed-source deployment continuation");
requireText(vercelIgnorePath, vercelIgnore, "scripts/vercel-ignore-build\\.sh$", "guard self-change deployment trigger");

const clerkConfig = read(clerkConfigPath);
requireText(clerkConfigPath, clerkConfig, "NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY", "Next.js Clerk publishable-key support");
requireText(clerkConfigPath, clerkConfig, "CLERK_PUBLISHABLE_KEY", "Clerk generic publishable-key fallback");
requireText(clerkConfigPath, clerkConfig, ".trim()", "environment normalization");
requireText(clerkConfigPath, clerkConfig, 'process.env.VERCEL_ENV === "production"', "production environment enforcement");
requireText(clerkConfigPath, clerkConfig, "production_requires_live_keys", "live-key production policy");
forbidText(clerkConfigPath, clerkConfig, "console.", "secret-adjacent logging in configuration parser");
forbidText(clerkConfigPath, clerkConfig, "process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY =", "runtime publishable-key environment mutation");
forbidText(clerkConfigPath, clerkConfig, "process.env.CLERK_PUBLISHABLE_KEY =", "runtime Clerk publishable-key environment mutation");
forbidText(clerkConfigPath, clerkConfig, "process.env.CLERK_SECRET_KEY =", "runtime Clerk secret-key environment mutation");

const identity = read(identityPath);
requireText(identityPath, identity, "prepareClerkRuntime()", "centralized runtime inspection");
requireText(identityPath, identity, "reasonCodes", "nonsecret diagnostic reason codes");
forbidText(identityPath, identity, "CLERK_SECRET_KEY", "direct secret-key handling outside centralized configuration");

const layout = read(layoutPath);
requireText(layoutPath, layout, 'import { prepareClerkRuntime } from "../lib/clerk-runtime-config"', "centralized Clerk layout configuration");
requireText(layoutPath, layout, "publishableKey={clerkRuntime.publishableKey}", "explicit validated publishable key");
forbidText(layoutPath, layout, "function isValidClerkConfiguration", "duplicated Clerk validator");

const proxy = read(proxyPath);
requireText(proxyPath, proxy, 'import { prepareClerkRuntime } from "./lib/clerk-runtime-config"', "centralized Clerk middleware readiness inspection");
requireText(proxyPath, proxy, "function authenticationReady()", "fail-closed Clerk readiness boundary");
requireText(proxyPath, proxy, "return prepareClerkRuntime().ready;", "side-effect-free Clerk readiness check");
requireText(proxyPath, proxy, "function preIdentityBoundary(request: NextRequest)", "pre-identity routing and regulated boundary");
requireText(proxyPath, proxy, "return regulatedMutationBoundary(request);", "regulated boundary before Clerk invocation");
requireText(proxyPath, proxy, "function getConfiguredClerkHandler()", "lazy Clerk middleware factory");
requireText(proxyPath, proxy, "configuredClerkHandler = clerkMiddleware(", "conditional Clerk middleware integration");
requireText(proxyPath, proxy, "await auth()", "protected-route Clerk authentication");
requireText(proxyPath, proxy, "export default async function proxy(request: NextRequest, event: NextFetchEvent)", "availability-safe proxy export");
requireText(proxyPath, proxy, "if (!authenticationReady())", "identity configuration readiness guard");
requireText(proxyPath, proxy, "return await getConfiguredClerkHandler()(request, event);", "configured Clerk delegation");
requireText(proxyPath, proxy, "catch {", "Clerk initialization/runtime failure containment");
requireText(proxyPath, proxy, "return identityConfigurationResponse(request);", "fail-closed identity fallback");
forbidText(proxyPath, proxy, "export default clerkMiddleware(", "unconditional Clerk middleware export");
forbidText(proxyPath, proxy, "function clerkPublishableEnvironment", "duplicated publishable-key validator");
forbidText(proxyPath, proxy, "function clerkSecretEnvironment", "duplicated secret-key validator");

const digest = sha256(sourceText);
const expectedHuman = renderMarkdown(data, digest);
const expectedDigest = `${digest}  CMMC-LEVEL-2-REV3-PRODUCTION-EVIDENCE.json\n`;

if (mode === "write") {
  fs.writeFileSync(humanPath, expectedHuman);
  fs.writeFileSync(digestPath, expectedDigest);
} else {
  if (read(humanPath) !== expectedHuman) fail(`${humanPath} drifted from machine-readable source`);
  if (read(digestPath) !== expectedDigest) fail(`${digestPath} drifted from machine-readable source`);
}

console.log(`Gate 34 passed: production identity availability isolation, canonical routing, bounded project-scoped production aliases, Rev. 3/CMMC evidence mapping, generated audit view, and SHA-256 no-drift controls verified (${digest}).`);
